							<h2>BANDWIDTH, INC. IT CAMPUS DEVELOPMENT</h2>
							<p> 
								ARCTC was formed in December 2020 in response to concerns about the rezoning of the land to be used by Bandwidth, Inc. and the resulting potential negative impacts to personal safety, water quality and the natural and recreational areas in the corridor. 
                            </p>
                            <p>
								Bandwidth, Inc. is a rapidly expanding Raleigh-based tech firm whose new corporate headquarters will be at the corner of Reedy Creek and Edwards Mill Roads.  The company produces communications software and is currently located on NCSU Centennial Campus.							
							</p>
							<p>
								The proposed campus will consist of multiple buildings including two five-story buildings, a Montessori school, athletic facilities and spaces with other amenities.  The project is managed by local real estate developers East West Partners, CBC Real Estate, and McAdams engineering. <a href="#map">See map below.</a
							</p>
							<h3>PROJECT SCHEDULE:</h3>
							<p>
							<ul>							
								<li><a href="https://cityofraleigh0drupal.blob.core.usgovcloudapi.net/drupal-prod/COR15/ASR-0085-2020_AA.pdf" target="_blank">Administrative Site Review</a> – approved April 21, 2021</li>
								<li>Groundbreaking ceremony held on July 19, 2021</li>
								<li>Site Permitting Review - completed November 22, 2021</li>
								<li>In May 2022, Bandwidth provided this schedule:
								    <ul style="list-style:circle;margin-bottom:0">
										<li>Construction from May 2021 to June 2023</li>
										<li>Move-in complete by end of Summer 2023</li>
										<li>Intermittent traffic disruptions along Reedy Creek and Edwards Mill Roads where road access will be limited but adequate passage to community traffic will be provided. 
											<ul style="list-style:square;margin-bottom:0">
												<li>Traffic impacts on Edwards Mill Road: 1/7/22 - 8/3/22</li>
												<li>Traffic impacts on Reedy Creek Road: 8/4/22 - 4/25/23</li>
											</ul>
										</li>
										<li>Disruptions in access to sidewalks and the existing multi-use greenway trail around the site. A public detour will be provided during sidewalk / multi-use path closures.
											<ul style="list-style:square;margin-bottom:0">
												<li>Access impacts to the multi-use path along and under Edwards Mill Road: 1/7/22 - 8/3/22</li>
												<li>Access impacts to the multi-use path along Reedy Creek Road: 8/4/22 - 4/25/23</li>
											</ul>
										</li>
                                  </ul>
								</li>
							</ul>
							</p>
							<h3>REZONING PROCESS</h3><p>
                              	Rezoning was needed to allow building of the Bandwidth campus. <span style="color:red;">On December 1, 2020, the Raleigh City Council voted 7 to 1 to approve rezoning of approximately 40 acres from Agricultural Production (AP) use to Office Mixed (OX-7) use, which allows seven-story maximum height buildings for office, retail space of up to 250,000 sq ft and up to 1,700 residential units.</span>  Council Member David Cox submitted the only disapproval vote.
							</p>
							<p>
								<span style="color:red;">This rezoning is inconsistent with the Future Land Use Map and the City Council received numerous emails and public comments requesting denial or additional evaluation of the rezoning request because the rezoning is</span>							
								<li>Incompatible with the surrounding natural, environmentally sensitive area</li>
								<li>Sets a precedence for development on land that was designated as Open Space</li>
								<li>Introduces potentially overwhelming and dangerous traffic volumes</li>
							</p>
							<p>	
								These concerns were supported by the staff Planning Report.	
							</p>
							<p>	
								To date, there is no public explanation of why the City Council approved zoning changes that exceed what Bandwidth has advertised as their plans for their headquarters campus.
							</p>
							<h3>ARCTC RESPONSE</h3><p>
                              	<span style="color:red;">On February 3, 2021, members of ARCTC met with Bandwidth representatives</span> to both welcome them to the neighborhood (an IT campus is preferable to a retail complex) and have a discussion of:  							
								<li><b>Description of the Project:</b>  The community would like to understand potential change to the area, along with the opportunity for the neighborhoods and Bandwidth to work collaboratively as good stewards of this unique area.</li>
								<li><b>Traffic Management:</b>  Traffic volume, traffic speed and safety, rush hour congestion, and conflicts with pedestrians, joggers, and bicyclists along Trenton and Reedy Creek Roads.</li>
								<li><b>Stormwater Management:</b>  Environmental health of Richland Creek drainage, Richland stormwater control lakes, and downstream impacts to existing streams, lakes, nearby forests and neighborhoods.</li>
								<li><b>Natural Area Preservation:</b>  Protection of the longevity and environmental health of Schenck Memorial Forest, NC State University farms/facilities on Reedy Creek and Trenton Roads, and William B. Umstead State Park.</li>
							</p>
							<p>	
								At the meeting, Bandwidth expressed their appreciation of the nearby greenway, park and natural areas and their belief that the new campus will not negatively impact the local neighborhoods or environment.   	
							</p>
							<p>	
								Because of Bandwidth’s lack of response to ARCTC’s questions and concerns, <span style="color:red;">members of ARCTC did extensive reviews and research into the Bandwidth site plan and worked to create alternative designs that would have less impact on the corridor.</span>  ARCTC members worked with Raleigh City, NC DOT, and local recreation groups during this effort. 
							</p>	
							<p>	
								<span style="color:red;">As part of the attempt to improve the site design, ARCTC requested a follow up meeting with representatives from ARCTC, Raleigh City, NC DOT, and Bandwidth to be facilitated by NC Representative Cynthia Ball.</span>  That meeting was held on March 26, 2021 and resulted in statements by NC DOT and Bandwidth representatives that the current design would not negatively impact the corridor.  No changes were made to address community concerns about traffic volume and traffic flow into and out of the new campus.     	
							</p>
							<p>	
								ARCTC continues to monitor the situation and is working to mitigate the anticipated impacts of increased traffic in the corridor. 
							</p>							
