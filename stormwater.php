							<h2>NC CONSTRUCTION SITE STORMWATER PERMITTING AND SITE STABILIZATION</h2>
							<p>In the Triangle area, where clay soils predominate, clay particles scoured by rainwater may result in brown-colored stormwater flowing directly off a new construction site or to an on-site sediment control basin. 
							</p>
							<p>Sediment-laden stormwater negatively impacts water quality downstream, with the corridor’s Richland Lake being a visible example.  Water quality standards enforced by the NC Department of Environmental Quality (DEQ) reduce the impact of stormwater by regulating turbidity, the degree of brown color caused by sediment in the water.  Turbidity is measured using a nephelometer, a device that shines a light beam through a water sample to detect the amount of light scattered by particles in the water.   More scattered light indicates higher turbidity, which is reported in Nephelometric Turbidity Units (NTUs).  DEQ regulations require that discharges to streams have a measurement of less than 50 NTUs (the water will appear misty).  For comparison, drinking water should be five NTUs or less. 
							</p>
							<p>On all one-acre or larger construction sites, DEQ requires owner/operators to have a North Carolina Construction General Permit requiring that they provide specified stormwater protection actions throughout project construction.  These actions include provision of large earthen basins and site stabilization.  The basins are constructed for pre/post construction stormwater control and are typically engineered to result in compliant discharges.  Without adequate vegetative or similar type stabilization, the stormwater treatment basins will be overloaded and unable to work as designed.  Proper site stabilization minimizes both stormwater volume and sediment concentration flowing to the stormwater basins. The owner/operator is required to implement and maintain stabilization measures that minimize erosion from exposed portions of the site, even if that stormwater flows to the sediment basin.
							</p>

