							<h2>LENOVO CENTER AREA DEVELOPMENT – REZONING OF AREA OUTLINED IN RED ABOVE</h2> 
													
							<h3>PROJECT DETAILS</h3>
							<p>
								There has been discussion for years about development near the Lenovo Center, and changes are now about to take place.  While the Lenovo Center is not in the corridor, anyone who has experienced the surge and gridlock in traffic during the NC State Fair or Lenovo Center events can appreciate the impacts of new development near the corridor. 
							</p>
							<p>
								The Centennial Authority and NC State University, City, County, and State representatives are collaborating to create a sports entertainment district associated with Carter Finley Stadium and providing new opportunities for staying, shopping, and dining in West Raleigh.   This district offers many options but must be intelligently developed.  
							</p>
							<p>
								The rezoning (Z-38-24) changes 80.7 acres from Commercial Mixed Use–12 Stories with Conditions (CX-12_CU) to Planned Development (PD) with an associated Master Plan which allows for a variety of building types across residential, institutional, commercial, and some industrial and open uses. The request includes four different districts: Arena/Parking (existing arena and parking), Entertainment (shopping, tailgating, dining, music), Mixed-Use (retail, dining, hotel), and Live/Work (office, apartments). Districts vary by maximum allowable height from 15 to 40 stories. The Master Plan proposes modifications to Unified Development Ordinance standards, including primary and side street setbacks, interior side and rear setbacks, parking and loading, building types, landscape and screening, streets and blocks, and signage.
							</p>
							<h3>CONCERNS</h3>	
								<p>
									<ul>
										<li>The building height change from 12 stories to 40 stories is a dramatic increase.</li>
										<li>Traffic gridlock is an area problem and this development will make it worse.  There are currently no required plans to substantially change the existing road infrastructure. </li>
										<li>The required traffic analysis needs to consider the other developments being planned for the area and periodic events like concerts and the NC State Fair.</li>
										<li>Downstream flood control Richland Lake and associated dam are under review because of functionality concerns.  The amount of sediment in Richland Lake continues to increase, especially from upstream construction projects.</li>
									</ul>
								</p>	
							<h3>STATUS</h3>	
								<p>During the April 1, 2025 Public Hearing, representatives from ARCTC, the Umstead Coalition, Cardinal Gibbons High School, and The Raleigh School all expressed general support for the project, but stated concerns about increased traffic, student safety, and negative impacts to nearby lakes and streams. On April 15, 2025, the Raleigh City Council unanimously approved the rezoning. 
								ARCTC continues to work with City Council members and the developer to help mitigate issues with the project.  In response to comments from City Council members and concerns expressed by the public, the developer included conditions with the rezoning proposal, which are summarized below.</p>
									<ul>
										<li><span style="font-weight:bold;">Periodic Public Meetings:</span> three public meetings where the developer will provide updates and receive public comments will be held and a report on each meeting will be provided to the appropriate Raleigh City personnel.  Required meeting notification is expanded to include specific listed groups such as ARCTC.  The developer will provide two annual reports on the project construction and anticipated traffic improvements.</li>
										<li><span style="font-weight:bold;">Bicycle and Pedestrian Access:</span> the site plan will include areas for bike racks, bike share, scooter share, or other comparable human-powered modes of transportation as well as bicycle amenity areas.  Lanes, pavement markings, or other delineations will be included for committed bicycle transportation.  Pedestrian access to the greenway will be considered. </li>
										<li><span style="font-weight:bold;">Stormwater Specifications:</span> development in special flood hazard areas will be subject to City of Raleigh UDO requirements.</li>
									</ul>
								</p>								
