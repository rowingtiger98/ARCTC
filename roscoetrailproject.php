							<h2>Rezoning Application Submitted for High-Density Development on Trenton Road</h2>
                            <p>In August 2025, development company Heritage Capital Partners submitted a rezoning application containing a maximum of 175 housing units for land on the Cary side of Trenton Road next to I-40.  This development will almost double the number of households in the corridor and will greatly increase traffic. Application 25-REZ-12 requests rezoning from Office and Institutional (O&I) to Residential Multi-Family-Conditional Use (RMF-CU).  View the application on the Town of Cary's website at <a href="https://www.carync.gov/connect-engage/transparency/public-hearings/public-hearing-cases/rezoning-cases-active-historic/2025-rezoning-cases" target="_blank">2025 Rezoning Cases</a>.</p> 
							<p>As part of Cary’s rezoning process, both a Public Hearing and a Neighborhood Meeting have been held. <span style="color:red;font-weight:bold;">At the April 30, 2026 Public Hearing, 11 residents, neighbors, and corridor users spoke in opposition to the rezoning.  The petition stating rezoning opposition and concerns with 342 signatures was provided to the Council members.</span>  Cary Mayor Harold Weinbrecht requested that the developer work with those expressing concern about the rezoning to resolve their differences.   At the Neighborhood Meeting held on September 3, 2025, a record 107 neighbors and corridor users attended and many expressed concerns and asked questions about the application. </p>
							<p> ARCTC is very concerned about this rezoning because</p>
                              <ul>
                              <li>The density of this project does not fit in the ARCTC area of high-tech campuses, single-family homes, and natural parks and streams that also attract a very active recreational community.  </li>
							  <li>Safety for both vehicles and people will become an issue if the road infrastructure is not available.</li>
							  <li>The road infrastructure needed to support the development is not currently planned and it would be very hard to fit the amount of lanes needed into the existing roads, especially on Trenton Road in Raleigh.</li>
                              <li>The ARCTC corridor functions as a single entity between Trinity and Edwards Mill Roads, so development on the Cary side of I-40 impacts the Raleigh side of I-40. </li>
                              <li>The traffic study associated with this project does not take into account the anticipated increase in traffic from Lenovo Center and Carter Finley or the impacts on the Raleigh side of Trenton Road. </li>
                              </ul>	    
                            </p>
							<p> The next step in Cary’s rezoning application process is review by the Planning and Zoning Board, which is not yet scheduled.  <span style="font-weight:bold;">In the meantime, Cary Town Council members are very interested in public comments and personal stories about why people oppose this current rezoning plan. </span> Please email your concerns to the Cary Town Council at <a href="mailto:town.council@carync.gov">town.council@carync.gov</a></p> 
